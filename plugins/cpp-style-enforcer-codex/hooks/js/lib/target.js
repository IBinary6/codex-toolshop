'use strict';

const path = require('path');

/** C/C++ source extensions, including headers. */
const CPP_EXTENSIONS = new Set(['.c', '.cc', '.cpp', '.cxx', '.h', '.hpp', '.hxx']);

/** Directories excluded from checks (third party, build outputs, package managers). */
const EXCLUDED_DIRS = new Set([
  'node_modules', 'build', 'dist', 'out', 'bin', 'obj',
  '.git', 'target', 'third_party', 'thirdparty', 'external',
  'vendor', 'deps', 'packages',
  '3rd', '3rdparty', '3rd_party', '3rd-party',
  'thirdpart', 'third-party', 'third_part', 'third-part',
  'thridpart', 'thridparty', 'thrid_party', 'thrid-party',
]);

/** Excluded filenames (generated by VS or not appropriate for styling). */
const SKIPPED_FILES = new Set(['resource.h', 'targetver.h', 'stdafx.h', 'pch.h']);

/**
 * Extract edited file paths from hook stdin JSON; a Codex apply_patch command may include multiple files.
 * Always return absolute paths: resolve relative paths against input.cwd (from the hook protocol; file_path is normally absolute)
 * to prevent misplaced repoRoot/configuration lookup or .clang-format generation.
 * @param {object} input
 * @returns {string[]}
 */
function resolveFilePaths(input) {
  if (!input || typeof input !== 'object') return [];
  const cwd = input.cwd || process.cwd();
  const toAbs = (p) => (path.isAbsolute(p) ? p : path.resolve(cwd, p));
  const paths = [];
  const add = (value) => {
    if (typeof value !== 'string' || !value.trim()) return;
    const resolved = toAbs(value.trim());
    if (!paths.includes(resolved)) paths.push(resolved);
  };
  const addPatchPaths = (patch) => {
    for (const line of patch.split(/\r?\n/)) {
      const match = line.match(/^\*\*\* (?:(?:Add|Update) File|Move to):\s+(.+?)\s*$/);
      if (match) add(match[1]);
    }
  };

  const t = input.tool_input;
  if (t && typeof t === 'object') {
    add(t.file_path || t.path || null);
    if (t.relative_path) add(t.relative_path);
    if (typeof t.command === 'string') {
      addPatchPaths(t.command);
    }
  } else if (typeof t === 'string') {
    if (t.trimStart().startsWith('*** Begin Patch')) addPatchPaths(t);
    else add(t);
  }
  add(input.file_path || input.path || null);
  return paths;
}

function resolveFilePath(input) {
  return resolveFilePaths(input)[0] || null;
}

/**
 * Process only files with matching extensions, not in SKIPPED_FILES or EXCLUDED_DIRS.
 * @param {string} filePath
 * @returns {boolean}
 */
function shouldHandle(filePath) {
  if (!filePath || typeof filePath !== 'string') return false;
  const ext = path.extname(filePath).toLowerCase();
  if (!CPP_EXTENSIONS.has(ext)) return false;
  if (SKIPPED_FILES.has(path.basename(filePath).toLowerCase())) return false;
  return !isExcludedPath(filePath);
}

/** Match complete path segments; do not exclude business paths merely containing vendor/thirdparty substrings. */
function isExcludedPath(filePath) {
  return typeof filePath === 'string' && filePath.split(/[/\\]/).slice(0, -1)
    .some((part) => EXCLUDED_DIRS.has(part.toLowerCase()));
}

module.exports = { resolveFilePath, resolveFilePaths, shouldHandle, isExcludedPath, CPP_EXTENSIONS, EXCLUDED_DIRS, SKIPPED_FILES };
