'use strict';

const fs = require('fs');
const path = require('path');

const CONTENT = `# Generated by cpp-style-enforcer — Google C++ Style
BasedOnStyle: Google
IndentWidth: 2
NamespaceIndentation: None
`;

/**
 * Generate a Google-style configuration when the full workflow applies and the project root lacks .clang-format.
 * Let VS, clangd, and this plugin read the same style configuration.
 *
 * - Do not generate when root is null (outside Git), since there is no reliable project root.
 * - Never overwrite an existing .clang-format or _clang-format (Windows-compatible name).
 * - Write UTF-8 without BOM using LF; catch failures without crashing.
 *
 * @param {string|null} root Git repository root
 */
function ensureClangFormatConfig(root) {
  if (!root) return;
  try {
    // clang-format inherits configuration from ancestors; do not create root configuration that masks an applicable style.
    let current = path.resolve(root);
    while (true) {
      if (fs.existsSync(path.join(current, '.clang-format'))
          || fs.existsSync(path.join(current, '_clang-format'))) return;
      const parent = path.dirname(current);
      if (parent === current) break;
      current = parent;
    }
    fs.writeFileSync(path.join(root, '.clang-format'), Buffer.from(CONTENT, 'utf-8'), { flag: 'wx' });
  } catch (_) {
    // Generation failure does not affect the main flow.
  }
}

module.exports = { ensureClangFormatConfig };
